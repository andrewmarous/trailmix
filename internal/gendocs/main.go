// Command gendocs generates operating-guide copies or checks for drift.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"strings"

	"trailmix/guide"
)

const start = "<!-- BEGIN GENERATED OPERATING GUIDE -->\n"
const end = "<!-- END GENERATED OPERATING GUIDE -->"

func main() {
	check := flag.Bool("check", false, "check generated documents without writing")
	flag.Parse()
	block := start + "<!-- Source: guide/operating-guide.md. Run make docs; do not edit this copy. -->\n\n" + guide.Text + "\n" + end
	readme, err := os.ReadFile("README.md")
	must(err)
	text := string(readme)
	a, b := strings.Index(text, start), strings.Index(text, end)
	if a < 0 || b < a {
		must(fmt.Errorf("README.md lacks operating-guide markers"))
	}
	outputs := map[string]string{
		"README.md":                text[:a] + block + text[b+len(end):],
		"AGENTS.md":                "<!-- Generated by make docs. -->\n\n" + block + "\n",
		"skills/trailmix/SKILL.md": "---\nname: trailmix\ndescription: Search shared Trailmix memory for prior decisions, preferences, procedures, and lessons. Save or correct notes only on explicit user request.\n---\n\n<!-- Generated by make docs. -->\n\nRead the operating guide with `tmix instructions` when the installed CLI differs from this skill.\n\n" + block + "\n",
	}
	for path, content := range outputs {
		if *check {
			existing, err := os.ReadFile(path)
			must(err)
			if !bytes.Equal(existing, []byte(content)) {
				must(fmt.Errorf("%s is stale; run make docs", path))
			}
		} else {
			must(os.WriteFile(path, []byte(content), 0644))
		}
	}
}

func must(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
